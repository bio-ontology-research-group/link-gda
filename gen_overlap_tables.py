ORDER = ["SimGIC","Resnik-BMA","Resnik-BMM","Lin-BMA","Lin-BMM","INDIGENA",
         "\\method{}-p","\\method{}-pf","\\method{}-pfs"]


def fmt(metric, mean, std):
    if metric == "MR":
        return f"{mean:.2f}\\std{{{std:.2f}}}"
    return f"{mean:.2f}\\std{{{std:.2f}}}"


def best(metric, stratum):
    """method with best (min MR / max otherwise) mean in this stratum."""
    vals = {m: DATA[m][stratum][metric][0] for m in ORDER}
    return min(vals, key=vals.get) if metric == "MR" else max(vals, key=vals.get)


def cell(method, stratum, metric):
    mean, std = DATA[method][stratum][metric]
    s = fmt(metric, mean, std)
    return f"\\f{{{s}}}" if best(metric, stratum) == method else s


def main_table(metrics=("MR", "MRR", "H@10")):
    print("% ---- MAIN stratified table (metrics: " + ",".join(metrics) + ") ----")
    for m in ORDER:
        cells = " & ".join(cell(m, st, me) for st in STRATA for me in metrics)
        print(f"    {m:<14} & {cells} \\\\")
        if m == "INDIGENA":
            print("    \\midrule")


def supp_table():
    print("\n% ---- SUPPLEMENT full table (all metrics, stratum = all) ----")
    for m in ORDER:
        cells = " & ".join(cell(m, "all", me) for me in METRICS)
        print(f"    {m:<14} & {cells} \\\\")
        if m == "INDIGENA":
            print("    \\midrule")


if __name__ == "__main__":
    main_table()
    supp_table()
